const dictionaries: Record<Language, Record<TranslationKey, string>> = {
  en: english,
  es: spanish,
  'pt-BR': portuguese
}

export function preferredLanguage(): Language {
  try {
    const saved = localStorage.getItem('smoi-language')
    if (saved === 'en' || saved === 'es' || saved === 'pt-BR') return saved
  } catch {
    return browserLanguage()
  }

  return browserLanguage()
}

function browserLanguage(): Language {
  const preferences = navigator.languages?.length ? navigator.languages : [navigator.language]

  for (const preference of preferences) {
    const code = preference.toLowerCase().split('-')[0]
    if (code === 'es') return 'es'
    if (code === 'pt') return 'pt-BR'
    if (code === 'en') return 'en'
  }

  return 'en'
}

export function translate(key: TranslationKey, values?: Record<string, string | number>): string {
  const template = dictionaries[preferredLanguage()][key]
  if (!values) return template
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    values[name] === undefined ? match : String(values[name])
  )
}

interface LanguageContextValue {
  language: Language
  setLanguage: (language: Language) => void
  t: (key: TranslationKey, values?: Record<string, string | number>) => string
}

const LanguageContext = createContext<LanguageContextValue | null>(null)

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguage] = useState<Language>(preferredLanguage)

  useEffect(() => {
    document.documentElement.lang = language
    try {
      localStorage.setItem('smoi-language', language)
    } catch {
      return
    }
  }, [language])

  const value = useMemo<LanguageContextValue>(() => ({
    language,
    setLanguage,
    t(key, values) {
      const template = dictionaries[language][key]
      if (!values) return template
      return template.replace(/\{(\w+)\}/g, (match, name: string) =>
        values[name] === undefined ? match : String(values[name])
      )
    }
  }), [language])

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export function useLanguage(): LanguageContextValue {
  const context = useContext(LanguageContext)
  if (!context) throw new Error('LanguageProvider is missing')
  return context
}
